def lookup(term: str) -> dict | None:
    """Find an entry by its title or any alias (case-insensitive)."""
    if not term:
        return None
    key = str(term).strip().lower()
    for title, e in TERMS.items():
        if title.lower() == key or key in (a.lower() for a in e.get("aliases", [])):
            return {"term": title, **e}
    return None


def tip(term: str) -> str:
    """One-line tooltip text for a term ('' if unknown)."""
    e = lookup(term)
    return e["short"] if e else ""


def by_group() -> dict:
    out = {g: [] for g in GROUPS}
    for title, e in TERMS.items():
        out.setdefault(e["group"], []).append({"term": title, **e})
    return out
